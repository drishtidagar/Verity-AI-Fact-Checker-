"""Offline regressions against the supplied 13-claim audit report.

These tests validate evidence attribution and pipeline invariants, not a hard-coded verdict
matrix for the Trap PDF. No Groq or Tavily API calls are made.
"""
import copy
import json
import unittest
from datetime import date
from pathlib import Path
from unittest.mock import patch

from app.services import evidence_rules as er, providers
from app.services.factcheck import (
    _source_note_grounded, assess_evidence, evidence_rating, gather_evidence,
)

REPORT = json.loads((Path(__file__).parent / "fixtures" / "latest_13_claim_report_2026-11-22.json").read_text(encoding="utf-8"))
UPLOADED_REPORT = json.loads((Path(__file__).parent / "fixtures" / "latest_uploaded_report_2026-11-22.json").read_text(encoding="utf-8"))


def finding(fragment):
    return next(x for x in REPORT["findings"] if fragment.lower() in x["claim"]["claim"].lower())


def uploaded_finding(fragment):
    return next(x for x in UPLOADED_REPORT["findings"] if fragment.lower() in x["claim"]["claim"].lower())


def replay(item, response=None, today=date(2026, 11, 22)):
    old = item["result"]
    evidence = copy.deepcopy(old.get("evidence", []))
    model = response or {k: copy.deepcopy(old.get(k)) for k in
                         ("verdict", "explanation", "corrected_fact", "conflicting_values", "evidence_quality", "source_notes")}
    if response is None:
        # Saved report values were generated by the deprecated hand-weighted heuristic, not the model.
        if "legacy" not in str(old.get("confidence_label", "")).lower():
            model["confidence"] = copy.deepcopy(old.get("confidence"))
        model["used_urls"] = copy.deepcopy(old.get("cited_urls") or old.get("used_urls") or [])
    with patch("app.services.factcheck.groq_json", return_value=model):
        result = assess_evidence(copy.deepcopy(item["claim"]), evidence, "offline-fixture", "offline-model", today=today)
    return result, evidence


class LatestReportAuditTests(unittest.TestCase):
    def test_legacy_report_score_is_not_replayed_as_model_confidence(self):
        result, _ = replay(finding("chemical formula of water"))
        self.assertIsNone(result["confidence"])
        self.assertIsNone(result["model_confidence"])

    def test_water_remains_verified_strong_and_source_authority_is_split_in_ui(self):
        result, evidence = replay(finding("chemical formula of water"))
        self.assertEqual((result["verdict"], result["evidence_rating"]), ("VERIFIED", "Strong"))
        self.assertEqual(result["not_counted"], [])
        self.assertEqual(set(result["support_summary"]["official_domains"]), {"noaa.gov", "nist.gov"})
        self.assertEqual(len(evidence), 5)
        self.assertEqual({e["source_type"] for e in evidence if e["domain"].endswith(("noaa.gov", "nist.gov"))},
                         {"Government"})
        from app.components.ui import _report_not_counted
        self.assertEqual(_report_not_counted({"not_counted": [], "retrieved_not_counted": [{"url": "stale"}]}, set()), [])

    def test_eiffel_explanation_and_trace_name_the_official_parliament_source(self):
        result, _ = replay(finding("Eiffel Tower"))
        self.assertIn("europarl.europa.eu", {x["domain"] for x in result["correction_sources"]})
        self.assertTrue(all(x["source_type"] in er.OFFICIAL_TYPES for x in result["correction_sources"]))
        self.assertIn("Paris", result["explanation"])
        self.assertIn("European Parliament", result["explanation"])
        self.assertNotIn("only the cited secondary", result["explanation"].lower())
        self.assertNotIn("secondary source", result["explanation"].lower())
        self.assertEqual(result["explanation"].count("Single-source finding"), 1)
        self.assertNotIn("Evidence limitation: this finding is supported", result["explanation"])

    def test_world_population_uses_secondary_current_estimates_and_excludes_old_unfpa_rows(self):
        result, _ = replay(finding("world's population"))
        unfpa_urls = {e["url"] for e in finding("world's population")["result"]["evidence"] if "unfpa.org" in e["url"]}
        self.assertTrue(unfpa_urls.isdisjoint(result["used_urls"]))
        excluded = {x["url"]: x["reason"] for x in result["not_counted"]}
        reasons = {excluded[url] for url in unfpa_urls if url in excluded}
        self.assertIn("outdated for claim", reasons)
        self.assertIn("projection not current", reasons)
        self.assertEqual(result["correction_check"], "secondary_only")
        self.assertFalse(result["correction_selection"]["official"])
        self.assertIn("No official 2026", result["explanation"])
        self.assertIn("historical figures", result["explanation"].lower())
        self.assertIn("projections", result["explanation"].lower())
        self.assertIn("not officially verified", result["explanation"].lower())

    def test_burj_height_explanation_does_not_call_a_secondary_value_authoritative(self):
        result, _ = replay(uploaded_finding("Burj Khalifa"))
        self.assertEqual(result["correction_check"], "secondary_only")
        self.assertIn("matadornetwork.com", result["explanation"])
        self.assertIn("not officially verified", result["explanation"].lower())
        self.assertNotIn("authoritative figure", result["explanation"].lower())
        self.assertNotIn("most recent and authoritative", result["explanation"].lower())

    def test_population_value_is_paired_to_its_own_year_not_a_neighboring_projection(self):
        source = {"url": "https://www.census.gov/world", "source_type": "Government", "relevance_score": 0.9,
                  "snippet": "The world population reached 8 billion in 2023, and the IDB projects it will reach 8.2 billion in July 2026, 9 billion by 2039."}
        rows = er.entity_year_quantities([source], ["world population", "global population"], 2026)
        self.assertEqual([(x["value_text"], x["value_type"]) for x in rows], [("8.2 billion", "projection")])
        self.assertIsNone(er.current_population_correction([source], ["world population", "global population"], 2026))

    def test_india_current_secondary_estimate_is_not_officially_verified(self):
        result, _ = replay(finding("India's population"))
        self.assertEqual(result["correction_check"], "secondary_only")
        self.assertFalse(result["correction_selection"]["official"])
        self.assertTrue(all(x["source_type"] not in er.OFFICIAL_TYPES for x in result["correction_sources"]))
        self.assertIn("No official 2026", result["explanation"])
        self.assertIn("not officially verified", result["explanation"].lower())
        self.assertTrue(all(x.get("year") == 2026 for x in result["correction_values"]))

    def test_co2_observations_are_counted_with_dates_units_and_series(self):
        result, evidence = replay(finding("carbon dioxide"))
        display_evidence = result["evidence"]
        by_domain = {er.registrable_domain(e["url"]): e for e in display_evidence}
        values = {row["domain"]: row for row in result["source_values"]}
        self.assertTrue({"nasa.gov", "noaa.gov"}.issubset(values))
        self.assertEqual(result["correction_check"], "supported")
        self.assertFalse(result["conflicting_values"])
        for domain in ("nasa.gov", "noaa.gov"):
            row = values[domain]
            self.assertEqual(row["unit"], "ppm")
            self.assertIn("2026", row["date"])
            self.assertTrue(row["series"])
            self.assertIn(row["url"], result["used_urls"])
            self.assertIn(row["value"].replace(" ", ""), by_domain[domain]["snippet"].replace(" ", ""))
        self.assertIn("separately dated measurement series", result["explanation"])

    def test_co2_correction_comes_from_primary_measurement_not_model_number(self):
        claim = {"claim": "Carbon dioxide is about 400 ppm.", "excerpt": "CO2 is about 400 ppm", "page": 1, "claim_type": "statistic"}
        url = "https://science.nasa.gov/earth/explore/earth-indicators/carbon-dioxide"
        evidence = [{"title": "Carbon Dioxide - Earth Indicator - NASA Science", "url": url,
                     "domain": "science.nasa.gov", "source_type": "Government", "relevance_score": 0.9,
                     "snippet": "Carbon dioxide concentration. Latest Measurement: 426 ppm. Latest Measurement Date: September 2026."}]
        model = {"verdict": "INACCURATE", "confidence": 75, "corrected_fact": "432 ppm",
                 "explanation": "Model proposed 432 ppm.", "conflicting_values": "", "evidence_quality": "HIGH",
                 "used_urls": [url], "source_notes": [{"url": url, "says": "426 ppm in September 2026", "stance": "contradicts"}]}
        with patch("app.services.factcheck.groq_json", return_value=model):
            result = assess_evidence(claim, evidence, "offline", "offline", today=date(2026, 11, 22))
        self.assertIn("426 ppm", result["corrected_fact"])
        self.assertNotIn("432 ppm", result["corrected_fact"])
        self.assertEqual(result["correction_check"], "supported")
        self.assertEqual(result["correction_sources"][0]["domain"], "nasa.gov")
        self.assertIn("September 2026", result["explanation"])

    def test_co2_conflict_requires_same_series_and_date(self):
        claim = {"claim": "Carbon dioxide is about 400 ppm.", "excerpt": "", "page": 1, "claim_type": "statistic"}
        evidence = []
        for domain, url, value in (("nasa.gov", "https://science.nasa.gov/co2", "426"),
                                   ("noaa.gov", "https://gml.noaa.gov/co2", "432")):
            evidence.append({"title": f"Global Monthly Mean CO2 {domain}", "url": url, "domain": domain,
                             "source_type": "Government", "relevance_score": 0.9,
                             "snippet": f"Carbon dioxide Global Monthly Mean {value} ppm July 2026."})
        model = {"verdict": "INACCURATE", "confidence": 70, "corrected_fact": "430 ppm", "explanation": "", 
                 "conflicting_values": "", "evidence_quality": "HIGH", "used_urls": [x["url"] for x in evidence],
                 "source_notes": [{"url": x["url"], "says": x["snippet"], "stance": "contradicts"} for x in evidence]}
        with patch("app.services.factcheck.groq_json", return_value=model):
            result = assess_evidence(claim, evidence, "offline", "offline", today=date(2026, 11, 22))
        self.assertTrue(result["conflicting_values"])
        self.assertEqual({x["date"] for x in result["source_values"]}, {"July 2026"})

    def test_pluto_attribution_uses_nasa_and_searches_for_an_independent_iau_source(self):
        result, _ = replay(finding("Pluto"))
        self.assertTrue(any(x["domain"].endswith("nasa.gov") for x in result["correction_sources"]))
        self.assertIn("NASA", result["explanation"])
        self.assertNotIn("only the cited secondary", result["explanation"].lower())
        claim = {"claim": "Pluto is a planet.", "excerpt": "Pluto is a planet.", "page": 1, "claim_type": "other"}
        nasa_url = "https://science.nasa.gov/dwarf-planets/pluto"
        iau_url = "https://www.iau.org/IAU/Iau/News/PR2006/iau-2006-general-assembly-resolution-votes.aspx"
        nasa = {"title": "Pluto", "url": nasa_url, "source_type": "Government", "snippet": "Pluto is a dwarf planet.", "relevance_score": 0.9}
        iau = {"title": "IAU Resolution", "url": iau_url, "source_type": providers.source_type(iau_url),
               "snippet": "Pluto is a dwarf planet under the IAU definition.", "relevance_score": 0.9}
        with patch("app.services.factcheck.tavily_search", side_effect=[[nasa], [iau]]) as search:
            gathered = gather_evidence(claim, "Pluto classification", "offline")
        self.assertEqual(search.call_count, 2)
        self.assertIn(iau_url, {x["url"] for x in gathered})
        self.assertEqual(providers.source_type(iau_url), "Official / institutional")

    def test_great_wall_collapses_two_nasa_urls_and_rejects_quora(self):
        result, evidence = replay(finding("Great Wall"))
        self.assertEqual(result["support_summary"]["independent_domains"].count("nasa.gov"), 1)
